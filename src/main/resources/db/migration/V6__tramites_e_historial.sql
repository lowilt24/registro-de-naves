-- =====================================================================
-- Sprint 5 — HU-09 (estado del tramite) y HU-10 (naves por estado)
--
-- Decisiones de la PO (13-10-2026) que fija esta migracion:
--   D2  seis estados y siete transiciones. Los estados quedan en un CHECK;
--       cambiarlos despues exige una V7.
--   D3  un tramite por nave. Esta migracion crea los que falten sin
--       duplicar aunque se ejecute dos veces; HU-03 lo crea al registrar.
--   D4  TRAMITES es la unica fuente oficial del estado del tramite.
--       nave.estado y la tabla solicitud (V1) se conservan sin tocar.
--
-- Propuestas que se aplican mientras la PO responde (ver LEEME-SPRINT5.md):
--   P1  el tramite nace en SOLICITUD_PRESENTADA.
--   P3  estado inicial de las naves existentes segun nave.estado.
--   P9  cada tramite creado aqui lleva una entrada inicial en el historial,
--       con estado anterior vacio y a nombre de quien registro la nave.
--
-- Consulta previa que pide el plan, sobre la base de desarrollo con los
-- datos de demo (13-10-2026):
--     SELECT estado, count(*) FROM nave GROUP BY estado;
--     REGISTRADA | 3
--
-- Todo el script es idempotente (IF NOT EXISTS y WHERE NOT EXISTS): si se
-- ejecuta dos veces, la segunda no crea ni duplica nada.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. TRAMITES: uno por nave
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tramites (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nave_id         BIGINT       NOT NULL,
    estado          VARCHAR(30)  NOT NULL DEFAULT 'SOLICITUD_PRESENTADA',
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Bloqueo optimista: si dos funcionarios cambian el mismo tramite a la
    -- vez, el segundo recibe 409 en lugar de pisar al primero.
    version         BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT fk_tramites_nave   FOREIGN KEY (nave_id) REFERENCES nave (id) ON DELETE CASCADE,
    -- D3: uno por nave. Tambien es lo que impide duplicar en el backfill.
    CONSTRAINT uk_tramites_nave   UNIQUE (nave_id),
    -- D2: los seis estados.
    CONSTRAINT ck_tramites_estado CHECK (estado IN (
        'SOLICITUD_PRESENTADA', 'EN_REVISION', 'OBSERVADA',
        'APROBADA', 'RECHAZADA', 'DESISTIDA'))
);

-- HU-10 filtra y cuenta por estado.
CREATE INDEX IF NOT EXISTS idx_tramites_estado ON tramites (estado);


-- ---------------------------------------------------------------------
-- 2. HISTORIAL_ESTADOS: quien, cuando, la accion, el estado anterior, el
--    nuevo y la observacion (regla adicional de D2).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS historial_estados (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id       BIGINT        NOT NULL,
    fecha            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    usuario_id       BIGINT        NOT NULL,
    accion           VARCHAR(20)   NOT NULL,
    -- Vacio solo en la entrada con que nace el tramite (P9).
    estado_anterior  VARCHAR(30),
    estado_nuevo     VARCHAR(30)   NOT NULL,
    observacion      VARCHAR(1000),

    CONSTRAINT fk_historial_tramite FOREIGN KEY (tramite_id) REFERENCES tramites (id) ON DELETE CASCADE,
    CONSTRAINT fk_historial_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    -- PRESENTAR: el tramite nace con HU-03. MIGRACION: lo creo esta V6.
    -- Las otras seis son las transiciones de la maquina.
    CONSTRAINT ck_historial_accion CHECK (accion IN (
        'PRESENTAR', 'MIGRACION',
        'ADMITIR', 'OBSERVAR', 'SUBSANAR', 'APROBAR', 'RECHAZAR', 'DESISTIR')),
    CONSTRAINT ck_historial_estado_anterior CHECK (estado_anterior IS NULL OR estado_anterior IN (
        'SOLICITUD_PRESENTADA', 'EN_REVISION', 'OBSERVADA',
        'APROBADA', 'RECHAZADA', 'DESISTIDA')),
    CONSTRAINT ck_historial_estado_nuevo CHECK (estado_nuevo IN (
        'SOLICITUD_PRESENTADA', 'EN_REVISION', 'OBSERVADA',
        'APROBADA', 'RECHAZADA', 'DESISTIDA')),
    -- Solo la entrada inicial puede ir sin estado anterior.
    CONSTRAINT ck_historial_inicial CHECK (
        (accion IN ('PRESENTAR', 'MIGRACION')) = (estado_anterior IS NULL))
);

CREATE INDEX IF NOT EXISTS idx_historial_tramite ON historial_estados (tramite_id, fecha, id);


-- ---------------------------------------------------------------------
-- 3. Backfill: un tramite por cada nave que todavia no lo tiene.
--
-- P3 (propuesta): el estado inicial sigue la situacion real de la nave.
--   REGISTRADA, DOCUMENTOS_CARGADOS -> SOLICITUD_PRESENTADA
--   EN_REVISION                     -> EN_REVISION
--   ABANDERADA                      -> APROBADA
--   RECHAZADA                       -> RECHAZADA
-- Cualquier otro valor (no deberia haber) cae en SOLICITUD_PRESENTADA,
-- que es el inicio de la maquina.
-- ---------------------------------------------------------------------
INSERT INTO tramites (nave_id, estado, creado_en, actualizado_en)
SELECT n.id,
       CASE n.estado
           WHEN 'EN_REVISION' THEN 'EN_REVISION'
           WHEN 'ABANDERADA'  THEN 'APROBADA'
           WHEN 'RECHAZADA'   THEN 'RECHAZADA'
           ELSE 'SOLICITUD_PRESENTADA'
       END,
       n.creado_en,
       n.creado_en
  FROM nave n
 WHERE NOT EXISTS (SELECT 1 FROM tramites t WHERE t.nave_id = n.id);


-- ---------------------------------------------------------------------
-- 4. P9 (propuesta): entrada inicial en el historial de los tramites que
--    no tienen ninguna. Estado anterior vacio, usuario = quien registro la
--    nave, fecha = cuando se registro.
-- ---------------------------------------------------------------------
INSERT INTO historial_estados (tramite_id, fecha, usuario_id, accion,
                               estado_anterior, estado_nuevo, observacion)
SELECT t.id,
       n.creado_en,
       n.registrado_por_id,
       'MIGRACION',
       NULL,
       t.estado,
       'Estado inicial asignado por la migracion V6 a partir del estado de la nave ('
           || n.estado || ').'
  FROM tramites t
  JOIN nave n ON n.id = t.nave_id
 WHERE NOT EXISTS (SELECT 1 FROM historial_estados h WHERE h.tramite_id = t.id);
