-- ---------------------------------------------------------------------
-- 4. Validacion del correo
--
-- La cuenta no inicia sesion hasta confirmar el correo. El token se
-- guarda como hash SHA-256, no en claro: si alguien lee la tabla no
-- puede usar los enlaces pendientes. Expira a las 24 horas.
-- ---------------------------------------------------------------------
ALTER TABLE usuario
    ADD COLUMN correo_validado  BOOLEAN     NOT NULL DEFAULT FALSE,
    ADD COLUMN token_validacion VARCHAR(64),
    ADD COLUMN token_expira_en  TIMESTAMPTZ;

