-- Sprint 10: etapa academica independiente del registro. No altera datos previos.
CREATE TABLE pp_solicitudes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nave_id BIGINT NOT NULL UNIQUE REFERENCES nave(id),
    registro_aprobacion_id BIGINT NOT NULL REFERENCES historial_estados(id),
    solicitante_id BIGINT NOT NULL REFERENCES usuario(id),
    procedencia VARCHAR(30) NOT NULL CHECK (procedencia IN ('REGISTRO_ANTERIOR','CONSTRUCCION','VENTA_JUDICIAL')),
    estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN ('BORRADOR','EN_REVISION','SUBSANACION','APROBADA')),
    requisitos_version INTEGER NOT NULL DEFAULT 1,
    requisitos_confirmados BOOLEAN NOT NULL DEFAULT FALSE,
    confirmacion_motivo VARCHAR(1000),
    ultimo_envio_id BIGINT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE pp_requisitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES pp_solicitudes(id),
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(180) NOT NULL,
    clase VARCHAR(20) NOT NULL CHECK (clase IN ('BASE','TECNICO','ADICIONAL')),
    motivo VARCHAR(1000) NOT NULL,
    tipo_origen VARCHAR(30) CHECK (tipo_origen IN ('CERTIFICADO_PROPIEDAD','PODER_NOTARIAL','ITC','SMC')),
    UNIQUE(solicitud_id,codigo)
);
CREATE TABLE pp_evidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES pp_solicitudes(id),
    requisito_id BIGINT NOT NULL REFERENCES pp_requisitos(id),
    version INTEGER NOT NULL CHECK (version>0),
    origen_documento_id BIGINT REFERENCES documentos(id),
    nombre_archivo VARCHAR(255) NOT NULL,
    contenido BYTEA NOT NULL,
    hash_sha256 VARCHAR(64) NOT NULL CHECK (length(hash_sha256)=64),
    tamano_bytes BIGINT NOT NULL CHECK (tamano_bytes>0 AND tamano_bytes<=10485760),
    creado_por BIGINT NOT NULL REFERENCES usuario(id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(requisito_id,version)
);
CREATE TABLE pp_envios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES pp_solicitudes(id),
    numero INTEGER NOT NULL,
    requisitos_version INTEGER NOT NULL,
    confirmacion_motivo VARCHAR(1000) NOT NULL,
    datos_nave TEXT NOT NULL,
    enviado_por BIGINT NOT NULL REFERENCES usuario(id),
    enviado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(solicitud_id,numero)
);
ALTER TABLE pp_solicitudes ADD CONSTRAINT fk_pp_ultimo_envio FOREIGN KEY (ultimo_envio_id) REFERENCES pp_envios(id);
CREATE TABLE pp_envio_items (
    envio_id BIGINT NOT NULL REFERENCES pp_envios(id),
    requisito_id BIGINT NOT NULL REFERENCES pp_requisitos(id),
    evidencia_id BIGINT NOT NULL REFERENCES pp_evidencias(id),
    nombre VARCHAR(180) NOT NULL,
    clase VARCHAR(20) NOT NULL,
    motivo VARCHAR(1000) NOT NULL,
    tipo_origen VARCHAR(30),
    PRIMARY KEY(envio_id,requisito_id),
    UNIQUE(envio_id,evidencia_id)
);
CREATE TABLE pp_revisiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envio_id BIGINT NOT NULL REFERENCES pp_envios(id),
    evidencia_id BIGINT NOT NULL REFERENCES pp_evidencias(id),
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('APROBADA','OBSERVADA')),
    observacion VARCHAR(1000),
    funcionario_id BIGINT NOT NULL REFERENCES usuario(id),
    funcionario_nombre VARCHAR(150) NOT NULL,
    revisado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(envio_id,evidencia_id),
    CHECK(decision<>'OBSERVADA' OR (observacion IS NOT NULL AND length(trim(observacion))>0))
);
CREATE TABLE pp_emisiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL UNIQUE REFERENCES pp_solicitudes(id),
    nave_id BIGINT NOT NULL UNIQUE REFERENCES nave(id),
    envio_id BIGINT NOT NULL REFERENCES pp_envios(id),
    numero VARCHAR(60) NOT NULL UNIQUE,
    emitido_en TIMESTAMPTZ NOT NULL,
    funcionario_id BIGINT NOT NULL REFERENCES usuario(id),
    funcionario_nombre VARCHAR(150) NOT NULL,
    datos_emitidos TEXT NOT NULL,
    contenido BYTEA,
    hash_sha256 VARCHAR(64),
    CHECK ((contenido IS NULL AND hash_sha256 IS NULL) OR (contenido IS NOT NULL AND length(hash_sha256)=64))
);
CREATE TABLE pp_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES pp_solicitudes(id),
    actor_id BIGINT NOT NULL REFERENCES usuario(id),
    actor_nombre VARCHAR(150) NOT NULL,
    actor_rol VARCHAR(30) NOT NULL,
    accion VARCHAR(40) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20),
    requisito_id BIGINT REFERENCES pp_requisitos(id),
    evidencia_id BIGINT REFERENCES pp_evidencias(id),
    envio_id BIGINT REFERENCES pp_envios(id),
    observacion VARCHAR(1000)
);
CREATE INDEX idx_pp_eventos_solicitud ON pp_eventos(solicitud_id,fecha,id);
CREATE INDEX idx_pp_envios_solicitud ON pp_envios(solicitud_id,numero);
CREATE INDEX idx_pp_evidencias_solicitud ON pp_evidencias(solicitud_id,requisito_id,version);
